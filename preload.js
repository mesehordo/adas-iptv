  pickFolder: () => ipcRenderer.invoke('pick-folder'),
  themeDirRead: (dir) => ipcRenderer.invoke('theme-dir-read', dir),
  themeDirOpen: (dir) => ipcRenderer.invoke('theme-dir-open', dir),
  scanFolder: (dir) => ipcRenderer.invoke('scan-folder', dir),
  readTextFile: (p) => ipcRenderer.invoke('read-text-file', p),

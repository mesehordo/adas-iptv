  openInPlayer: (items, name) => ipcRenderer.invoke('open-in-player', { items, name }),
  mediaAvailable: () => ipcRenderer.invoke('media-available'),
  mediaStatus: () => ipcRenderer.invoke('media-status'),
  mediaProbe: (url) => ipcRenderer.invoke('media-probe', url),
  mediaStart: (plan) => ipcRenderer.invoke('media-start', plan),
  mediaStop: (id) => ipcRenderer.invoke('media-stop', id),
  recStart: (o) => ipcRenderer.invoke('rec-start', o),
